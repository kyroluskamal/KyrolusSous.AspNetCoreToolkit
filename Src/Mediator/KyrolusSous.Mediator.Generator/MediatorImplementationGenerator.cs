            sb.AppendLine(Indent8OpenBrace);
            sb.AppendLine("            await foreach (var item in source.WithCancellation(cancellationToken).ConfigureAwait(false))");
            sb.AppendLine(Indent12OpenBrace);
            sb.AppendLine("                if (item is null)");
            sb.AppendLine(Indent16OpenBrace);
            sb.AppendLine("                    if (default(TResponse) is not null)");
            sb.AppendLine(Indent16OpenBrace);
            sb.AppendLine("                        throw new InvalidCastException($\"[KyrolusMediator] Stream handler for {requestType.FullName} returned null, but expected non-nullable {typeof(TResponse).FullName}.\");");
            sb.AppendLine(Indent16CloseBrace);
            sb.AppendLine();
            sb.AppendLine("                    yield return (TResponse)(object)default!;");
