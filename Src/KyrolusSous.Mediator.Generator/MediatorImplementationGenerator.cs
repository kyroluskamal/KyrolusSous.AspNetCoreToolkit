        /// <summary>
        /// Generates the DI extension method for registering all discovered concrete handlers.
        /// </summary>
        private static string GenerateHandlerRegistrationMethod(List<HandlerInfo> handlerInfos, List<OpenGenericHandlerInfo> openGenericHandlers, HashSet<string> namespaces)
        {
            var sb = new StringBuilder();
            sb.AppendLine(AutoGeneratedHeader);
            sb.AppendLine(NullableEnable);
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
            // Add using statements for handler namespaces collected previously
            foreach (var ns in namespaces.Where(n => !n.StartsWith("System") && !n.StartsWith("Microsoft") && !n.StartsWith("KyrolusSous.Mediator")) // Avoid redundant usings
                                        .OrderBy(n => n))
            {
                sb.AppendLine($"using {ns};");
            }
            sb.AppendLine();
            // Place in a common namespace for extensions
            sb.AppendLine("namespace Microsoft.Extensions.DependencyInjection");
            sb.AppendLine(OpenBrace);
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Extension methods for registering KyrolusSous.Mediator handlers discovered by the generator.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine(CompilerGeneratedAttribute);
            sb.AppendLine("    [System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)]");
            sb.AppendLine("    public static class KyrolusMediatorGeneratedHandlersDIExtensions");
            sb.AppendLine(Indent4OpenBrace);
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Registers all concrete Command and Query handlers discovered by the KyrolusSous.Mediator.Generator.");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        public static IServiceCollection AddKyrolusMediatorHandlers(this IServiceCollection services)");
            sb.AppendLine(Indent8OpenBrace);

            // Loop through all discovered handlers and add registration lines
            foreach (var info in handlerInfos)
            {
                string handlerFullName = info.HandlerType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                // Register the concrete handler type. Transient lifetime is typical for handlers.
                sb.AppendLine($"            services.TryAddTransient<{handlerFullName}>();");

                // --- Optional: Registering against specific interfaces ---
                // You might also want to register the handler against its specific closed-generic interface
                // although resolving the concrete type directly is often sufficient if dependencies ask for the concrete type.
                // If you need to resolve handlers via their specific interface (e.g., IEnumerable<IKyrolusQueryHandler<...>>), uncomment below.
                // string interfaceFullName = info.InterfaceFullName; 
                // sb.AppendLine($"            services.TryAddTransient<{interfaceFullName}, {handlerFullName}>();");
                // --- End Optional ---
            }

            sb.AppendLine();
            // Register open generic handlers
            foreach (var info in openGenericHandlers)
            {
                string interfaceType = GetOpenGenericTypeOf(info.InterfaceType);
                string handlerType = GetOpenGenericTypeOf(info.HandlerType);
                sb.AppendLine($"            services.TryAddTransient(typeof({interfaceType}), typeof({handlerType}));");
            }
            sb.AppendLine();
            sb.AppendLine("            return services;");
            sb.AppendLine(Indent8CloseBrace);
            sb.AppendLine(Indent4CloseBrace);
            sb.AppendLine(CloseBrace);
            return sb.ToString();
        }

        private static string GetOpenGenericTypeOf(INamedTypeSymbol symbol)
        {
            string ns = symbol.ContainingNamespace.ToDisplayString();
            string name = symbol.Name;
            int arity = symbol.Arity;
            string typeParams = arity == 0 ? string.Empty : $"<{new string(',', arity - 1)}>";
            return $"global::{ns}.{name}{typeParams}";
        }
