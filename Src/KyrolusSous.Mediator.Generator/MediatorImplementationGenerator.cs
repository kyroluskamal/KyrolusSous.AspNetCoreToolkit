        /// <summary>
        /// Analyzes a class symbol to determine if it implements one of the KyrolusMediator handler interfaces
        /// and extracts the request and response types.
        /// </summary>
        private static HandlerInfo? TryGetHandlerInfo(INamedTypeSymbol handlerSymbol, HandlerInterfaceDefinitions defs)
        {
            // Iterate through all interfaces (including inherited ones)
            foreach (var iface in handlerSymbol.AllInterfaces)
            {
                // Ensure it's a constructed generic type (e.g., IKyrolusCommandHandler<MyCommand, Unit>)
                if (!iface.IsGenericType || iface.ConstructedFrom == null) continue;

                if (!TryMatchHandlerInterface(iface, defs, out var reqType, out var resType, out var isStream))
                {
                    continue;
                }
                string ifaceName = iface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat); // Get full name like IKyrolusCommandHandler<NS.Req, NS.Resp>

                // If a match was found and types were extracted successfully
                if (reqType != null && resType != null)
                {
                    return new HandlerInfo(handlerSymbol, reqType, resType, ifaceName, isStream);
                }
            }
            return null; // Not a recognized handler interface implementation
        }

        private static bool TryMatchHandlerInterface(
            INamedTypeSymbol iface,
            HandlerInterfaceDefinitions defs,
            out INamedTypeSymbol? reqType,
            out ITypeSymbol? resType,
            out bool isStream)
        {
            reqType = null;
            resType = null;
            isStream = false;

            var originalDef = iface.OriginalDefinition; // Get the unbound generic definition (e.g., IKyrolusCommandHandler<,>)
            if (iface.TypeArguments.Length == 2)
            {
                if (SymbolEqualityComparer.Default.Equals(originalDef, defs.QueryHandlerDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.CommandHandlerWithResponseDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.RequestHandlerDef))
                {
                    reqType = iface.TypeArguments[0] as INamedTypeSymbol;
                    resType = iface.TypeArguments[1];
                    return true;
                }
                if (SymbolEqualityComparer.Default.Equals(originalDef, defs.StreamRequestHandlerDef))
                {
                    reqType = iface.TypeArguments[0] as INamedTypeSymbol;
                    resType = iface.TypeArguments[1];
                    isStream = true;
                    return true;
                }
                return false;
            }

            if (iface.TypeArguments.Length == 1 &&
                (SymbolEqualityComparer.Default.Equals(originalDef, defs.CommandHandlerDef) ||
                 SymbolEqualityComparer.Default.Equals(originalDef, defs.RequestHandlerWithoutResponseDef)))
            {
                reqType = iface.TypeArguments[0] as INamedTypeSymbol;
                resType = defs.UnitSymbol;
                return true;
            }

            return false;
        }

        private static IEnumerable<OpenGenericHandlerInfo> TryGetOpenGenericHandlerRegistrations(
            INamedTypeSymbol handlerSymbol,
            HandlerInterfaceDefinitions defs)
        {
            foreach (var iface in handlerSymbol.AllInterfaces)
            {
                if (!iface.IsGenericType || iface.ConstructedFrom is null) continue;

                var originalDef = iface.OriginalDefinition;
                if (SymbolEqualityComparer.Default.Equals(originalDef, defs.QueryHandlerDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.CommandHandlerDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.CommandHandlerWithResponseDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.RequestHandlerDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.RequestHandlerWithoutResponseDef) ||
                    SymbolEqualityComparer.Default.Equals(originalDef, defs.StreamRequestHandlerDef))
                {
                    yield return new OpenGenericHandlerInfo(handlerSymbol.OriginalDefinition, originalDef);
                }
            }
        }

        /// <summary>
        /// Generates the source code for the static GeneratedMediatorDispatcher class.
        /// </summary>
        private static string GenerateStaticDispatcherCode(List<HandlerInfo> handlerInfos, INamedTypeSymbol unitSymbol, HashSet<string> namespaces)
        {
            var sb = new StringBuilder();
            // --- File Header ---
            sb.AppendLine(AutoGeneratedHeader);
            sb.AppendLine(NullableEnable);
            sb.AppendLine();

            // --- Using Statements ---
            foreach (var ns in namespaces.OrderBy(n => n)) sb.AppendLine($"using {ns};");
            sb.AppendLine();

            // --- Namespace and Class Definition ---
            sb.AppendLine("namespace KyrolusSous.Mediator.Generated");
            sb.AppendLine(OpenBrace);
            sb.AppendLine(CompilerGeneratedAttribute);
            sb.AppendLine("    internal static class GeneratedMediatorDispatcher");
            sb.AppendLine(Indent4OpenBrace);

            // --- Dictionaries ---
            var streamHandlerCount = handlerInfos.Count(info => info.IsStream);
            sb.AppendLine($"        private static readonly Dictionary<Type, Func<object, IServiceProvider, CancellationToken, Task>> s_commandDispatchers = new({handlerInfos.Count});");
            sb.AppendLine($"        private static readonly Dictionary<Type, Func<object, IServiceProvider, CancellationToken, Task<object>>> s_requestDispatchers = new({handlerInfos.Count});");
            sb.AppendLine($"        private static readonly Dictionary<Type, Func<object, IServiceProvider, CancellationToken, IAsyncEnumerable<object>>> s_streamDispatchers = new({streamHandlerCount});");
            sb.AppendLine();

            // --- Static Constructor ---
            sb.AppendLine("        static GeneratedMediatorDispatcher()");
            sb.AppendLine(Indent8OpenBrace);

            // --- Populate Dictionaries ---
            foreach (var info in handlerInfos)
            {
                string hFullName = info.HandlerType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string rFullName = info.RequestType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string iFullName = info.InterfaceFullName;
                bool isCmd = info.ResponseType.Equals(unitSymbol, SymbolEqualityComparer.Default);

                sb.AppendLine($"            // Handler: {hFullName} Request: {rFullName}");
                if (info.IsStream)
                {
                    sb.AppendLine($"            s_streamDispatchers[typeof({rFullName})] = (req, sp, ct) =>");
                    sb.AppendLine($"            {{ var handler = ({iFullName})sp.GetRequiredService<{hFullName}>(); return CastStreamToObject(handler.Handle(({rFullName})req, ct), ct); }};");
                }
                else if (isCmd)
                {
                    sb.AppendLine($"            s_commandDispatchers[typeof({rFullName})] = async (req, sp, ct) =>");
                    sb.AppendLine($"            {{ var handler = ({iFullName})sp.GetRequiredService<{hFullName}>(); await handler.Handle(({rFullName})req, ct); }};");
                }
                else
                {
                    sb.AppendLine($"            s_requestDispatchers[typeof({rFullName})] = async (req, sp, ct) =>");
                    sb.AppendLine($"            {{ var handler = ({iFullName})sp.GetRequiredService<{hFullName}>(); var result = await handler.Handle(({rFullName})req, ct); return (object)result!; }};");
                }
                sb.AppendLine();
            }
            sb.AppendLine(Indent8CloseBrace); // End static constructor
            sb.AppendLine();

            // --- Dispatch Methods ---
            GenerateDispatchMethod(sb, isCommand: true, unitSymbol);
            GenerateDispatchMethod(sb, isCommand: false, unitSymbol);
            GenerateStreamDispatchMethod(sb);

            sb.AppendLine(Indent4CloseBrace); // End class
            sb.AppendLine(CloseBrace); // End namespace
            return sb.ToString();
        }

        /// <summary>
        /// Generates the implementation class for the internal IGeneratedDispatcher interface.
        /// </summary>
        private static string GenerateDispatcherImplementation(INamedTypeSymbol generatedDispatcherInterfaceSymbol)
        {
            var sb = new StringBuilder();
            string interfaceFullName = generatedDispatcherInterfaceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string interfaceNamespace = generatedDispatcherInterfaceSymbol.ContainingNamespace.ToDisplayString();

            sb.AppendLine(AutoGeneratedHeader);
            sb.AppendLine(NullableEnable);
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Threading;");
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine($"using {interfaceNamespace}; // Namespace of IGeneratedDispatcher");
            sb.AppendLine();
            sb.AppendLine("namespace KyrolusSous.Mediator.Generated"); // Keep in Generated namespace
            sb.AppendLine(OpenBrace);
            sb.AppendLine("    /// <summary>Implements the internal dispatcher interface by delegating to the static dispatcher.</summary>");
            sb.AppendLine(CompilerGeneratedAttribute);
            sb.AppendLine($"    internal sealed class GeneratedDispatcher : {interfaceFullName}");
            sb.AppendLine(Indent4OpenBrace);
            sb.AppendLine("        public Task<TResponse> DispatchRequestAsync<TResponse>(object request, IServiceProvider sp, CancellationToken ct)");
            sb.AppendLine("            => GeneratedMediatorDispatcher.DispatchRequestAsync<TResponse>(request, sp, ct);");
            sb.AppendLine();
            sb.AppendLine("        public Task DispatchCommandAsync(object command, IServiceProvider sp, CancellationToken ct)");
            sb.AppendLine("            => GeneratedMediatorDispatcher.DispatchCommandAsync(command, sp, ct);");
            sb.AppendLine();
            sb.AppendLine("        public IAsyncEnumerable<TResponse> DispatchStreamAsync<TResponse>(object request, IServiceProvider sp, CancellationToken ct)");
            sb.AppendLine("            => GeneratedMediatorDispatcher.DispatchStreamAsync<TResponse>(request, sp, ct);");
            sb.AppendLine(Indent4CloseBrace);
            sb.AppendLine(CloseBrace);
            return sb.ToString();
        }

        /// <summary>
        /// Generates the DI extension method for registering the IGeneratedDispatcher implementation.
        /// </summary>
        private static string GenerateDIRegistration(INamedTypeSymbol generatedDispatcherInterfaceSymbol)
        {
            var sb = new StringBuilder();
            string interfaceFullName = generatedDispatcherInterfaceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string implementationFullName = "KyrolusSous.Mediator.Generated.GeneratedDispatcher"; // Full name of the implementation class
            string interfaceNamespace = generatedDispatcherInterfaceSymbol.ContainingNamespace.ToDisplayString();

            sb.AppendLine(AutoGeneratedHeader);
            sb.AppendLine(NullableEnable);
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
            sb.AppendLine($"using {interfaceNamespace}; // Namespace of IGeneratedDispatcher");
            sb.AppendLine($"using KyrolusSous.Mediator.Generated; // Namespace of GeneratedDispatcher implementation");
            sb.AppendLine();
            // Put extensions in a relevant namespace, e.g., Microsoft.Extensions.DependencyInjection for discoverability
            sb.AppendLine("namespace Microsoft.Extensions.DependencyInjection");
            sb.AppendLine(OpenBrace);
            sb.AppendLine("    /// <summary>Extension methods for registering generated KyrolusSous.Mediator components.</summary>");
            sb.AppendLine(CompilerGeneratedAttribute);
            sb.AppendLine("    [System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)]"); // Hide from intellisense? Optional
            sb.AppendLine("    public static class KyrolusMediatorGeneratedDIExtensions");
            sb.AppendLine(Indent4OpenBrace);
            sb.AppendLine("        /// <summary>Registers the generated dispatcher implementation.</summary>");
            sb.AppendLine("        /// <remarks>Call this after registering handlers and before resolving IKyrolusMediatorSender.</remarks>");
            sb.AppendLine("        public static IServiceCollection AddKyrolusMediatorGeneratedDispatcher(this IServiceCollection services)");
            sb.AppendLine(Indent8OpenBrace);
            // Replace any existing dispatcher (e.g., reflection-based) with the generated one
            sb.AppendLine($"            services.Replace(ServiceDescriptor.Singleton<{interfaceFullName}, {implementationFullName}>());");
            sb.AppendLine("            return services;");
            sb.AppendLine(Indent8CloseBrace);
            sb.AppendLine(Indent4CloseBrace);
            sb.AppendLine(CloseBrace);
            return sb.ToString();
        }
