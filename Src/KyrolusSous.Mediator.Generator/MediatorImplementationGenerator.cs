            }

            sb.AppendLine("            Type? openGenericHandlerType = null;");
            sb.AppendLine($"            if ({inputParamName} is IKyrolusCommandBase)");
            sb.AppendLine(Indent12OpenBrace);
            sb.AppendLine($"                openGenericHandlerType = typeof(IKyrolusCommandHandler<,>).MakeGenericType({localRequestVarName}, typeof(TResponse));");
