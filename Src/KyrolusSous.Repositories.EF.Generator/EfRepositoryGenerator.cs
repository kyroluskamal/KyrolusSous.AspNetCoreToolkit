        private string? CalculateSoftDelete(RepositoryRequest request)
        {
            if (request.EnableSoftDeleteSpecified)
            {
                if (request.EnableSoftDelete)
                    return "true";
                else return null;
            }
            else
            {
                if (!request.HasSoftDeleteProperty)
                    return null;
                return "(policy.EnableSoftDeleteDefault ?? false)";
            }
        }
        private bool ValidateKeyProperties(SourceProductionContext context, RepositoryRequest request, IPropertySymbol[] entityProperties)
        {
            var missing = request.KeyPropertyNames
                .Where(k => !entityProperties.Any(p => string.Equals(p.Name, k, StringComparison.Ordinal)))
                .ToArray();
            if (missing.Length == 0) return true;

            context.ReportDiagnostic(Diagnostic.Create(KeyPropertyMissingDescriptor, Location.None,
                string.Join(", ", missing), request.EntityType.ToDisplayString()));
            return false;
        }
        private bool ValidateDefaultIncludes(SourceProductionContext context, RepositoryRequest request, IPropertySymbol[] entityProperties)
        {
            if (request.DefaultIncludes.Length == 0) return true;
            var missing = request.DefaultIncludes
                .Where(include => !entityProperties.Any(p => string.Equals(p.Name, include, StringComparison.Ordinal)))
                .ToArray();
            if (missing.Length == 0) return true;
            context.ReportDiagnostic(Diagnostic.Create(DefaultIncludeMissingDescriptor, Location.None,
                string.Join(", ", missing), request.EntityType.ToDisplayString()));
            return false;
        }
        private bool ValidateSoftDeleteProperty(SourceProductionContext context, RepositoryRequest request)
        {
            if (!request.EnableSoftDelete) return true;
            if (string.IsNullOrWhiteSpace(request.SoftDeleteProperty)) return true;
            if (request.HasSoftDeleteProperty) return true;
            context.ReportDiagnostic(Diagnostic.Create(SoftDeleteMissingDescriptor, Location.None,
                request.SoftDeleteProperty, request.EntityType.ToDisplayString()));
            return false;
        }
        private bool ValidateRowVersionProperty(SourceProductionContext context, RepositoryRequest request, IPropertySymbol[] entityProperties)
        {
            if (string.IsNullOrWhiteSpace(request.RowVersionProperty)) return true;
            var exists = entityProperties.Any(p => string.Equals(p.Name, request.RowVersionProperty, StringComparison.Ordinal));
            if (exists) return true;
            context.ReportDiagnostic(Diagnostic.Create(RowVersionMissingDescriptor, Location.None,
                request.RowVersionProperty!, request.EntityType.ToDisplayString()));
            return false;
        }

