            context.AddSource("GeneratedRepositoriesServiceCollectionExtensions.g.cs", SourceText.From(diSb.ToString(), Encoding.UTF8));
        }

        private void GenerateRepository(StringBuilder sb, RepositoryRequest request)
        {
            var keyProps = BuildKeyProps(request);
            var keyNamesLiteral = BuildKeyNamesLiteral(request);
            var keyDisplayFromEntity = BuildKeyDisplayFromEntity(keyProps);
            var entityProperties = GetMutableProperties(request);
            var rowRevisionProp = FindRowVersion(request, entityProperties);
            UsingDirectives(sb, request);

            sb.AppendLine($"namespace {request.Namespace}");
            sb.AppendLine("{");

            ClassName(sb, request);
            GetAllAsync(sb, request);
            QueryAsync(sb, request);
            GetPagedDefaults(sb, request);
            GetByIdAsync(sb, request, keyNamesLiteral);
            CompiledQueries(sb, request, keyProps);
            AddAsync(sb, request);
            AddRangeAsync(sb, request);
            ExistAsync(sb, request);
            PatchAsync(sb, request, keyProps, keyNamesLiteral, rowRevisionProp);
            RemoveAsync(sb, request, keyProps, keyNamesLiteral);
