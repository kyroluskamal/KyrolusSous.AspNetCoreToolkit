        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx =>
            {
                ctx.AddSource("KyrolusEfRepositoryAttribute.g.cs", SourceText.From(GeneratorAttribute, Encoding.UTF8));
            });
            var classesWithAttribute = context.SyntaxProvider.ForAttributeWithMetadataName(
                $"{AttributeNamespace}.{AttributeName}",
                predicate: static (_, _) => true,
                transform: static (ctx, _) => new ClassInfo((INamedTypeSymbol)ctx.TargetSymbol, ctx.Attributes[0])
            );

            var compilationAndClasses = context.CompilationProvider.Combine(classesWithAttribute.Collect());

            context.RegisterSourceOutput(compilationAndClasses, Execute);
        }

        private void Execute(SourceProductionContext context, (Compilation compilation, ImmutableArray<ClassInfo> classes) tuple)
        {
            var (_, classesInfo) = tuple;
            var diNamespaces = new HashSet<string>(StringComparer.Ordinal);
            var diRegistrations = new List<string>();
            var unitOfWorkMap = new Dictionary<INamedTypeSymbol, List<RepositoryRequest>>(SymbolEqualityComparer.Default);

            foreach (var classInfo in classesInfo)
            {
                if (!TryBuildRepositoryRequest(context, classInfo, out var request))
                {
                    continue;
                }

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated />");
                sb.AppendLine("#nullable enable");
                sb.AppendLine();
                GenerateRepository(sb, request);
                context.AddSource($"{request.RepositoryName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
                EmitQueryHelpers(context, request);

                // Collect DI info
                diNamespaces.Add(request.Namespace);
                diRegistrations.Add($$"""            services.AddScoped<{{request.RepositoryName}}>();""");
                var repoInterface = request.KeyPropertyNames.Length == 1
                    ? $"IKyrolusSingleKeyRepositoryAsync<{request.DbContextType.ToDisplayString()}, {request.EntityType.ToDisplayString()}, {request.KeyType.ToDisplayString()}>"
                    : $"IKyrolusCompositeKeyRepositoryAsync<{request.DbContextType.ToDisplayString()}, {request.EntityType.ToDisplayString()}, {request.KeyType.ToDisplayString()}>";
                diRegistrations.Add($"""            services.AddScoped<{repoInterface}, {request.RepositoryName}>();""");
                diRegistrations.Add($$"""            services.AddScoped<IQueryHelper<{{request.EntityType.ToDisplayString()}}>, {{request.EntityType.Name}}QueryHelper>();""");

                if (!unitOfWorkMap.TryGetValue(request.DbContextType, out var list))
                {
                    list = [];
                    unitOfWorkMap[request.DbContextType] = list;
                }
                list.Add(request);
            }

            // Emit DI extension once with all generated repos
            EmitDiExtension(context, diNamespaces, diRegistrations);
            EmitUnitOfWorks(context, unitOfWorkMap);
        }

        private bool TryBuildRepositoryRequest(SourceProductionContext context, ClassInfo classInfo, out RepositoryRequest request)
        {
            request = default!;
            var classSymbol = classInfo.ClassSymbol;
            var attributeData = classInfo.AttributeData;
            if (classSymbol is null || attributeData is null)
            {
                return false;
            }

            if (!TryParseAttributeRequest(attributeData, out var parsedRequest, out var errorMessage))
            {
                context.ReportDiagnostic(Diagnostic.Create(new DiagnosticDescriptor(
                    id: "EFREP001",
                    title: "GenerateEfRepositoryAttribute Error",
                    messageFormat: errorMessage ?? "Unknown error parsing GenerateEfRepositoryAttribute",
                    category: "KyrolusSous.Repositories.EF.Abstractions.Generator",
                    DiagnosticSeverity.Error,
                    isEnabledByDefault: true),
                    Location.None));
                return false;
            }

            var entityProperties = GetEntityProperties(parsedRequest);
            parsedRequest.HasSoftDeleteProperty = entityProperties.Any(p => string.Equals(p.Name, parsedRequest.SoftDeleteProperty, StringComparison.Ordinal));
            var allValid = ValidateKeyProperties(context, parsedRequest, entityProperties)
                && ValidateDefaultIncludes(context, parsedRequest, entityProperties)
                && ValidateSoftDeleteProperty(context, parsedRequest)
                && ValidateRowVersionProperty(context, parsedRequest, entityProperties);
            if (!allValid)
            {
                return false;
            }

            request = parsedRequest;
            return true;
        }

        private static void EmitDiExtension(SourceProductionContext context, HashSet<string> diNamespaces, List<string> diRegistrations)
        {
            if (diRegistrations.Count == 0) return;

