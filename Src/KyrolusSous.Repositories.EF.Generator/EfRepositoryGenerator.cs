                .Select(p => p.Name)
                .ToArray();

            var orderProps = allProps.Select(p => p.Name).ToArray();

            return new PropertyBuckets
            {
                StringProps = stringProps,
                NavProps = navProps,
                OrderProps = orderProps,
                NumericProps = numericProps,
                DateProps = dateProps,
                BoolProps = boolProps,
                GuidProps = guidProps,
                EnumProps = enumProps
            };
        }

        private static string NumericMethod(RepositoryRequest request, (string Name, ITypeSymbol Type, bool IsNullable) p)
        {
            var tName = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var valueAccess = p.IsNullable ? $"e.{p.Name}{ValueSuffix}" : $"e.{p.Name}";
            var guard = p.IsNullable ? $"e.{p.Name}{HasValueSuffix} && " : string.Empty;
            return $$"""
        private static Expression<Func<{{request.EntityType.ToDisplayString()}}, bool>>? NumericPredicate_{{p.Name}}(string op, string value)
        {
            if (!{{tName}}.TryParse(value, NumberStyles.Any, CultureInfo.InvariantCulture, out var parsed)) return null;
            return op.ToLowerInvariant() switch
            {
                "eq" => e => {{guard}}{{valueAccess}} == parsed,
                "gt" => e => {{guard}}{{valueAccess}} > parsed,
                "gte" => e => {{guard}}{{valueAccess}} >= parsed,
                "lt" => e => {{guard}}{{valueAccess}} < parsed,
                "lte" => e => {{guard}}{{valueAccess}} <= parsed,
                _ => throw new ArgumentException($"Unsupported operator '{op}' for '{{p.Name}}'")
            };
        }
""";
        }

