            diSb.AppendLine("using KyrolusSous.Repositories.EF.Abstractions.Query;");
            foreach (var ns in diNamespaces)
            {
                diSb.AppendLine($"using {ns};");
            }
            diSb.AppendLine();
            diSb.AppendLine("namespace KyrolusSous.Repositories.EF.Generated");
            diSb.AppendLine("{");
            diSb.AppendLine("    public static class GeneratedRepositoriesServiceCollectionExtensions");
            diSb.AppendLine("    {");
            diSb.AppendLine("        public static IServiceCollection AddGeneratedKyrolusRepositories(this IServiceCollection services)");
            diSb.AppendLine("        {");
